// کامپوننت LanguageProvider برای فراهم کردن Context زبان در سراسر برنامه
export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>('fa');
  const [hydrated, setHydrated] = useState(false); // تا قبل از خواندن مقدار ذخیره‌شده، چیزی در localStorage نمی‌نویسیم

  // خواندن زبان ذخیره‌شده پس از هیدریشن (سازگار با SSR)
  useEffect(() => {
    const savedLang = localStorage.getItem('language') as Language | null;
    if (savedLang === 'fa' || savedLang === 'en') {
      setLanguage(savedLang);
    } else {
      const browserLang = navigator.language.split('-')[0];
      setLanguage(browserLang === 'fa' ? 'fa' : 'en');
    }
    setHydrated(true);
  }, []);

  // تعیین جهت‌دهی (RTL/LTR) بر اساس زبان
  const isRTL = language === 'fa';

  // ذخیره زبان در localStorage و به‌روزرسانی ویژگی dir در تگ html
  useEffect(() => {
    // باگ قبلی: این effect در اولین رندر مقدار پیش‌فرض ('fa') را روی انتخاب ذخیره‌شدهٔ کاربر می‌نوشت و انتخاب او هر بار پاک می‌شد
    if (hydrated) localStorage.setItem('language', language);
    document.documentElement.setAttribute('lang', language);
    document.documentElement.setAttribute('dir', isRTL ? 'rtl' : 'ltr');
  }, [language, isRTL, hydrated]);

  // تابع ترجمه (پایدار تا از رندر بی‌نهایت جلوگیری شود)
  const t = useCallback(
    (key: string) => translations[language]?.[key] || key,
    [language],
  );

  const value = useMemo(
    () => ({ language, setLanguage, isRTL, t }),
    [language, isRTL, t],
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

// هوک سفارشی برای استفاده از Context زبان
export function useLanguage() {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
